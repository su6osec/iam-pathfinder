"""Markdown renderer - README snippets, PR comments, docs."""

from __future__ import annotations

from ..rules.base import Finding
from .report import Report


def _cell(text: str) -> str:
    """Escape text so it survives inside a markdown table cell."""
    return str(text).replace("|", "\\|").replace("\n", " ")


def _finding_section(index: int, finding: Finding) -> list[str]:
    lines = [
        f"### {index}. `{finding.rule_id}` - {finding.principal_type} "
        f"`{finding.principal_name}`",
        "",
        f"- **Severity:** {finding.severity.label}"
        + (" (conditional)" if finding.conditional else ""),
        f"- **Confidence:** {finding.confidence}",
        f"- **Title:** {_cell(finding.title)}",
        f"- **Required permissions:** {', '.join(f'`{p}`' for p in finding.permissions) or '-'}",
        "",
        "**What it means.** " + finding.explanation,
        "",
        "**Evidence.**",
        "",
    ]
    if finding.evidence:
        for ev in finding.evidence:
            statement = ", ".join(f"`{k}`: `{v}`" for k, v in sorted(ev.statement.items()))
            lines.append(f"- {ev.source_label} - {statement}")
    else:
        lines.append("- (no policy statement attached)")
    lines.extend(
        [
            "",
            "**Remediation.** " + finding.remediation,
        ]
    )
    if finding.notes:
        lines.extend(["", "**Notes.**", ""])
        lines.extend(f"- {note}" for note in finding.notes)
    lines.append("")
    return lines


def render(report: Report) -> str:
    scope = report.scope
    counts = report.severity_counts
    lines: list[str] = [
        f"# IAM analysis - account {report.account_id or 'unknown'}",
        "",
        f"> Generated by iam-pathfinder {report.tool_version} from "
        f"`{report.export_path or 'stdin'}`. Offline analysis of a local export; "
        "no AWS API calls were made.",
        "",
        "## Summary",
        "",
        "| Metric | Value |",
        "| --- | --- |",
        f"| Findings | {len(report.findings)} |",
        f"| Critical | {counts['critical']} |",
        f"| High | {counts['high']} |",
        f"| Medium | {counts['medium']} |",
        f"| Low | {counts['low']} |",
        f"| Users / groups / roles | {scope['users']} / {scope['groups']} / "
        f"{scope['roles']} |",
        f"| Managed policies | {scope['managed_policies']} |",
        f"| Escalation paths | {len(report.paths)} |",
        "",
        "## Findings by rule",
        "",
        "| Rule | Count |",
        "| --- | --- |",
    ]
    if report.rule_counts:
        for rule_id, count in report.rule_counts.items():
            lines.append(f"| `{rule_id}` | {count} |")
    else:
        lines.append("| - | 0 |")

    lines.extend(["", "## Findings", ""])
    if not report.findings:
        lines.append("No findings at or above the severity filter.")
        lines.append("")
    else:
        for index, finding in enumerate(report.findings, start=1):
            lines.extend(_finding_section(index, finding))

    lines.extend(["## Escalation paths", ""])
    if not report.paths:
        lines.append("No path from a principal to full administrative control was found.")
        lines.append("")
    else:
        for index, path in enumerate(report.paths, start=1):
            steps = [f"`{path.start}`"]
            for step in path.steps:
                if step.kind == "assume":
                    steps.append(f"assume `{step.target}`")
                else:
                    steps.append(f"escalate via `{step.rule_id}` to `{step.target}`")
            lines.append(
                f"{index}. ({path.length} hop{'s' if path.length != 1 else ''}) "
                + " -> ".join(steps)
            )
        lines.append("")
        lines.append("Path details:")
        lines.append("")
        for index, path in enumerate(report.paths, start=1):
            lines.append(f"{index}. `{path.start}`")
            for step in path.steps:
                kind = "assume" if step.kind == "assume" else f"escalate ({step.rule_id})"
                lines.append(f"   - {kind} -> `{step.target}`: {step.detail}")
        lines.append("")
    return "\n".join(lines)
