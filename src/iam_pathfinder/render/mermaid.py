"""Mermaid renderer - renders the escalation graph as ``graph TD``.

The output is plain Mermaid text: paste it into any Markdown file or Mermaid
live editor.  Node ids are sanitised to ``[A-Za-z0-9_]`` so labels containing
ARN punctuation cannot break the diagram.
"""

from __future__ import annotations

import re

from .report import Report


def _safe_id(node_id: str, index: int) -> str:
    cleaned = re.sub(r"[^A-Za-z0-9_]", "_", node_id)
    if not cleaned or cleaned[0].isdigit():
        cleaned = f"n_{cleaned}"
    return f"{cleaned}_{index}"


def _escape_label(text: str) -> str:
    return text.replace('"', "'").replace("\n", " ").replace("|", "/")


def render(report: Report) -> str:
    graph = report.graph
    lines = [
        "%% Escalation graph generated by iam-pathfinder "
        f"{report.tool_version} (offline analysis, no AWS API calls)",
        "%% solid arrow = sts:AssumeRole edge, thick arrow = escalation "
        "capability edge",
        "graph TD",
    ]

    ids: dict[str, str] = {}
    ordered = sorted(graph.nodes.values(), key=lambda n: (n.kind, n.label))
    for index, node in enumerate(ordered):
        node_id = _safe_id(node.id, index)
        ids[node.id] = node_id
        label = _escape_label(f"{node.label} ({node.kind})")
        lines.append(f'    {node_id}["{label}"]')

    for edge in graph.edges:
        source = ids[edge.source]
        target = ids[edge.target]
        if edge.kind == "assume":
            lines.append(f'    {source} -->|"{_escape_label("assume")}"| {target}')
        else:
            label = _escape_label(f"escalate {edge.rule_id or ''}".strip())
            lines.append(f'    {source} ==>|"{label}"| {target}')

    lines.append('    classDef virtual fill:#4c1d95,stroke:#312e81,color:#ffffff;')
    virtual = ids.get("virtual:admin")
    if virtual:
        lines.append(f"    class {virtual} virtual;")

    lines.append("")
    lines.append("%% Escalation paths:")
    if not report.paths:
        lines.append("%%   (none)")
    else:
        for path in report.paths:
            chain = " -> ".join(
                [path.start]
                + [f"{s.target} [{s.rule_id or s.kind}]" for s in path.steps]
            )
            lines.append(
                f"%%   ({path.length} hop{'s' if path.length != 1 else ''}) "
                f"{_escape_label(chain)}"
            )
    return "\n".join(lines) + "\n"
