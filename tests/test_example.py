"""The bundled example account must keep demonstrating every rule."""

from __future__ import annotations

import json
import re
from pathlib import Path

from conftest import EXAMPLE

from iam_pathfinder.analyzer import analyze_account
from iam_pathfinder.graph import build_graph, find_paths
from iam_pathfinder.parser import load_export
from iam_pathfinder.render import FORMATS, Report, render
from iam_pathfinder.rules import ALL_RULES

REPO = Path(__file__).resolve().parent.parent


def _report() -> Report:
    parsed = load_export(EXAMPLE)
    ctx, findings = analyze_account(parsed.account)
    graph = build_graph(ctx, findings)
    return Report(
        ctx=ctx,
        findings=findings,
        paths=find_paths(graph),
        graph=graph,
        export_path="examples/vulnerable-account.json",
    )


class TestExampleExport:
    def test_parses_cleanly(self):
        parsed = load_export(EXAMPLE)
        assert parsed.account.account_id == "123456789012"
        assert parsed.unresolved_policy_arns == []
        assert len(parsed.account.users) == 6
        assert len(parsed.account.groups) == 4
        assert len(parsed.account.roles) == 5
        assert len(parsed.account.managed_policies) == 4

    def test_contains_only_synthetic_account_ids(self):
        raw = EXAMPLE.read_text(encoding="utf-8")
        account_ids = set(re.findall(r'"arn:aws:iam::(\d{12}):', raw))
        # The cross-account trust entry uses an obviously fake account.
        assert account_ids <= {"123456789012", "999999999999"}, account_ids
        # No real-looking identifiers: user/role ids are the synthetic AIDA/AROA
        # prefixes generated by examples/generate_example.py.
        ids = set(re.findall(r'"(?:UserId|RoleId|PolicyId)": "([A-Za-z0-9]+)"', raw))
        assert ids, "expected synthetic ids in the example"
        assert all(re.fullmatch(r"(?:AIDA|AROA|AGPA|ANPA)[0-9a-f]{12}", i) for i in ids)

    def test_generator_is_deterministic(self):
        """Regenerating the example must not rewrite it with different bytes."""
        import subprocess
        import sys

        before = EXAMPLE.read_bytes()
        subprocess.run(
            [sys.executable, str(REPO / "examples" / "generate_example.py")],
            check=True,
            capture_output=True,
        )
        after = EXAMPLE.read_bytes()
        assert before == after, "examples/generate_example.py is not deterministic"


class TestExampleAnalysis:
    def test_every_rule_fires(self):
        report = _report()
        fired = {f.rule_id for f in report.findings}
        expected = {rule.id for rule in ALL_RULES}
        assert fired == expected, (
            "the example must trigger every rule; missing: "
            f"{sorted(expected - fired)}, unexpected: {sorted(fired - expected)}"
        )

    def test_report_counts(self):
        report = _report()
        assert len(report.findings) == 27
        counts = report.severity_counts
        assert counts["critical"] == 1
        assert counts["high"] == 17
        assert counts["medium"] == 8
        assert counts["low"] == 1

    def test_has_a_multi_hop_path(self):
        report = _report()
        assert len(report.paths) == 19
        two_hop = [p for p in report.paths if p.length == 2]
        assert two_hop, "the example must demonstrate a multi-hop path"
        path = two_hop[0]
        assert path.start == "user:alice"
        assert [s.kind for s in path.steps] == ["assume", "escalate"]
        assert path.steps[0].target == "role:AdminRole"
        assert path.end == "virtual:admin"

    def test_all_findings_have_evidence_and_remediation(self):
        report = _report()
        for finding in report.findings:
            assert finding.explanation, finding.rule_id
            assert finding.remediation, finding.rule_id
            assert finding.evidence, f"{finding.rule_id} has no evidence"
            assert finding.permissions, finding.rule_id

    def test_every_format_renders_the_example(self):
        report = _report()
        for fmt in FORMATS:
            text = render(fmt, report)
            assert text.strip(), fmt
        assert len(json.loads(render("json", report))["findings"]) == 27
        assert len(json.loads(render("sarif", report))["runs"][0]["results"]) == 27
        assert "graph TD" in render("mermaid", report)
        assert render("html", report).startswith("<!DOCTYPE html>")
